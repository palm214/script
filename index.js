let islamicTexts = [...new Set(fallbackLibrary.map(text => text.trim()).filter(Boolean))];
let textIndex = 0;

function shuffleArray(array) {
    for (let i = array.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [array[i], array[j]] = [array[j], array[i]];
    }
}

shuffleArray(islamicTexts);

function getNextIslamicText() {
    if (textIndex >= islamicTexts.length) {
        shuffleArray(islamicTexts);
        textIndex = 0;
    }

    return islamicTexts[textIndex++];
}

