async function replyToLatestComment() {
    try {
        const latestComment = await getLatestComment(ANIME_ID);

        if (!latestComment) {
            console.log(
                `⚠️ [أنمي ${ANIME_ID}] لم يتم العثور على تعليقات.`
            );
            return;
        }

        const commentId = getCommentId(latestComment);

        if (!commentId) {
            console.log(
                `⚠️ [أنمي ${ANIME_ID}] تعذر استخراج ID لأحدث تعليق.`
            );
            return;
        }

        if (
            REPLY_ONLY_TO_NEW_COMMENT &&
            lastCommentId === commentId
        ) {
            console.log(
                `⏭️ [أنمي ${ANIME_ID}] لا يوجد تعليق أحدث من السابق.`
            );
            return;
        }

        const replyText = buildReplyText();

        if (!replyText) {
            console.log('⚠️ لا يوجد نص لإرساله.');
            return;
        }

        console.log(
            `\n📬 [أنمي ${ANIME_ID}] أحدث تعليق ID: ${commentId}`
        );
        console.log(`✉️ الرد: ${replyText}`);

        await axios.post(
            `${MAIN_BASE_URL}create-anime-comment-reply`,
            {
                anime_comment_id: commentId,
                reply_text: replyText,
                spoiler: 'No'
            },
            {
                timeout: 30000,
                headers: {
                    'User-Agent':
                        'Dalvik/2.1.0 (Linux; U; Android 11; Build/RP1A.200720.011)',
                    'Content-Type': 'application/json',
                    'Client-Id': CLIENT_ID,
                    'Client-Secret': CLIENT_SECRET,
                    'X-Requested-With': 'com.anslayer.app',
                    'Authorization': `Bearer ${TOKEN}`
                }
            }
        );

        lastCommentId = commentId;

        console.log(
            `✅ [أنمي ${ANIME_ID}] تم نشر الرد بنجاح.`
        );
    } catch (error) {
        const status = error?.response?.status;

        const apiMessage =
            error?.response?.data?.message ||
            error?.response?.data?.error ||
            '';

        console.log(
            `❌ فشل التنفيذ [أنمي ${ANIME_ID}]` +
            (status ? ` | HTTP ${status}` : '') +
            (apiMessage ? ` | ${apiMessage}` : '')
        );
    }
}

