let textsQueue = [];

function shuffleArray(arr) {
    for (let i = arr.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [arr[i], arr[j]] = [arr[j], arr[i]];
    }
}

function getNextText() {
    if (textsQueue.length === 0) {
        textsQueue = [...VALID_TEXTS];
        shuffleArray(textsQueue);
        console.log('🔄 بدأت دورة جديدة من النصوص.');
    }
    return textsQueue.pop();
}

// ==========================================
// دالة إرسال التعليق
// ==========================================
async function postComment() {
    try {
        const params = { anime_id: ANIME_ID, _offset: 0, _limit: 1 };
        const commentsRes = await axios.get(
            `${BASE_URL}get-anime-comments?json=${encodeURIComponent(JSON.stringify(params))}`,
            {
                headers: {
                    'User-Agent': 'Dalvik/2.1.0 (Linux; U; Android 11; Build/RP1A.200720.011)',
                    'Client-Id': CLIENT_ID,
                    'Client-Secret': CLIENT_SECRET,
                    'X-Requested-With': 'com.anslayer.app'
                }
            }
        );

        const resBody = commentsRes.data?.response;
        let commentsList = [];
        if (Array.isArray(resBody)) commentsList = resBody;
        else if (resBody && Array.isArray(resBody.data)) commentsList = resBody.data;

        if (commentsList.length === 0) {
            console.log('⚠️ لا توجد تعليقات في الأنمي 2025.');
            return;
        }

        const firstCommentId = commentsList[0].anime_comment_id || commentsList[0].comment_id || commentsList[0].id;
        if (!firstCommentId) {
            console.log('⚠️ لم يتم العثور على معرف التعليق الأول.');
            return;
        }

        const replyText = getNextText();
        console.log(`\n📬 جارٍ إرسال رد: "${replyText.substring(0, 40)}..."`);

        await axios.post(
            `${BASE_URL}create-anime-comment-reply`,
            {
                anime_comment_id: firstCommentId,
                reply_text: replyText,
                spoiler: "No"
            },
            {
                headers: {
                    'User-Agent': 'Dalvik/2.1.0 (Linux; U; Android 11; Build/RP1A.200720.011)',
                    'Content-Type': 'application/json',
                    'Client-Id': CLIENT_ID,
                    'Client-Secret': CLIENT_SECRET,
                    'X-Requested-With': 'com.anslayer.app',
                    'Authorization': `Bearer ${TOKEN}`
                }
            }
        );
        console.log(`✅ تم إرسال: ${replyText.substring(0, 35)}...`);
    } catch (error) {
        console.log('❌ فشل إرسال الرد:', error.response?.data?.detail || error.message);
    }
}

