async function getLatestComment(animeId) {
    const jsonQuery = encodeURIComponent(
        JSON.stringify({
            anime_id: animeId,
            page: 1
        })
    );

    const response = await axios.get(
        `${MAIN_BASE_URL}get-anime-comments?json=${jsonQuery}`,
        {
            timeout: 30000,
            headers: {
                'User-Agent':
                    'Dalvik/2.1.0 (Linux; U; Android 11; Build/RP1A.200720.011)',
                'Client-Id': CLIENT_ID,
                'Client-Secret': CLIENT_SECRET,
                'X-Requested-With': 'com.anslayer.app'
            }
        }
    );

    const comments = getCommentsArray(response.data);
    return findLatestComment(comments);
}

